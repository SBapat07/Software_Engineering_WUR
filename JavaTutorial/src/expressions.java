
public class expressions {

	public static void main(String[] args) {
		
//		expression = operands + operators
//		operands = values, variables, numbers, quantity, etc.
//		operators = +, -, *, /, %
		
		int friends = 10;
		
		friends = friends + 1;
		
		System.out.println(friends);

		friends = friends - 3;
		
		System.out.println(friends);
		
		friends = friends * 2;
		
		System.out.println(friends);
		
		friends = friends % 3;
		
		System.out.println(friends);
		
		//Short hand way of increment and decrement
		
		friends++;
		
		System.out.println(friends);
		
		friends--;
		System.out.println(friends);
		
//		double friends = 10;
//		
//		friends = (double)friends/3;
//		
//		System.out.println(friends);
		
	}

}
